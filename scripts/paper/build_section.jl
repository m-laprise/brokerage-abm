"""
    scripts/paper/build_section.jl

Assemble the publication-ready results section. Inputs: paper/section_source.tex
(canonical prose with \\pv{key} and \\pvcaption{name} references),
paper/captions.tex (hand-edited figure titles and captions),
output/main/values.tex (data values, generated by scripts/paper/stats.jl),
output/main/convergence/values.tex (generated by audit_convergence.jl),
output/main/figmeta.tex (display conventions, generated by scripts/paper/figures.jl),
output/ridge/paired/analysis/paper_values.tex (generated by ridge_supplement.jl),
output/ridge/ablations/analysis/paper_values.tex (generated by analyze_ablations.jl),
output/assessment_access/paper_values.tex (generated from the retained experiment),
paper/supplement.tex (supplementary figure labels and their order),
and the figures in output/main/figures/. Output: output/main/results_section.tex, a flattened,
\\input-ready fragment with literal numbers and captions inlined.
Reported estimates use at most two decimal places and percentages use whole
percentage points. Exact parameter settings retain their source precision.

The build fails loudly on: a \\pv reference with no definition, duplicate value
definitions, a \\pvcaption reference with no caption block, a caption block never
referenced, or a missing figure file. It then compiles the fragment inside a
throwaway wrapper as a smoke test. Unquoted values in the retained statistical
catalogue are reported but do not require reanalysis when the prose changes.

Usage: julia --project --threads=auto scripts/paper/build_section.jl
"""

using Dates
using Printf: @sprintf

include(joinpath(@__DIR__, "..", "reporting_provenance.jl"))

const PAPER = normpath(joinpath(@__DIR__, "..", "..", "paper"))
const GENERATED = normpath(joinpath(@__DIR__, "..", "..", "output", "main"))
const SRC = joinpath(PAPER, "section_source.tex")
const VALS = joinpath(GENERATED, "values.tex")
const CONVERGENCE_VALS = joinpath(GENERATED, "convergence", "values.tex")
const RIDGE_VALS = normpath(
    joinpath(GENERATED, "..", "ridge", "paired", "analysis", "paper_values.tex")
)
const ABLATION_VALS = normpath(
    joinpath(GENERATED, "..", "ridge", "ablations", "analysis", "paper_values.tex")
)
const ASSESSMENT_ACCESS_VALS = normpath(
    joinpath(GENERATED, "..", "assessment_access", "paper_values.tex")
)
const FIGMETA = joinpath(GENERATED, "figmeta.tex")
const CAPS = joinpath(PAPER, "captions.tex")
const SUPPLEMENT = joinpath(PAPER, "supplement.tex")
const OUT = joinpath(GENERATED, "results_section.tex")
const REPORTING_PROVENANCE = manuscript_git_provenance(
    normpath(joinpath(@__DIR__, "..", ".."));
    sources=(
        @__FILE__,
        "paper/section_source.tex",
        "paper/captions.tex",
        "paper/supplement.tex",
    ),
)

fail(msg) = (println("BUILD FAILED: ", msg); exit(1))

"""Round displayed estimates and percentages without changing exact parameter settings."""
function display_value(key::AbstractString, value::AbstractString)
    key in ("aaRho", "aaDelta", "aaEta") && return value
    decimal = match(r"^[+-]?\d+\.(\d+)$", value)
    isnothing(decimal) && return value
    percentage = endswith(key, "Percent")
    !percentage && length(decimal[1]) <= 2 && return value
    number = parse(BigFloat, value)
    shown = percentage ? @sprintf("%.0f", number) : @sprintf("%.2f", number)
    # A rounded zero has no meaningful direction.
    if iszero(parse(BigFloat, shown))
        return percentage ? "0" : "0.00"
    end
    return startswith(value, "+") ? "+" * shown : shown
end

isfile(SRC) || fail("missing $SRC")
isfile(VALS) || fail("missing $VALS (run scripts/paper/stats.jl first)")
isfile(CONVERGENCE_VALS) ||
    fail("missing $CONVERGENCE_VALS (run scripts/paper/audit_convergence.jl first)")
isfile(RIDGE_VALS) ||
    fail("missing $RIDGE_VALS (run scripts/paper/ridge_supplement.jl first)")
isfile(ABLATION_VALS) ||
    fail("missing $ABLATION_VALS (run scripts/ridge/analyze_ablations.jl first)")
isfile(ASSESSMENT_ACCESS_VALS) || fail(
    "missing $ASSESSMENT_ACCESS_VALS (run scripts/assessment_access/paper_values.jl first)",
)
isfile(FIGMETA) || fail("missing $FIGMETA (run scripts/paper/figures.jl first)")
isfile(CAPS) || fail("missing $CAPS (hand-edited caption source)")
isfile(SUPPLEMENT) || fail("missing $SUPPLEMENT (supplementary figure labels)")
const INPUT_PROVENANCE = analysis_input_provenance(
    REPORTING_PROVENANCE,
    (VALS, CONVERGENCE_VALS, RIDGE_VALS, ABLATION_VALS, ASSESSMENT_ACCESS_VALS, FIGMETA),
)
any(first(record) == "nn-ridge comparison analysis commit"
    for record in recorded_analysis_commits(RIDGE_VALS)) ||
    fail("Ridge values lack paired-comparison provenance")

# sweep id: taken from the header stats.jl writes into values.tex, so the
# provenance always names the data actually used
valsrc = read(VALS, String)
sweepm = match(r"% sweep: (\S+)", valsrc)
SWEEP = isnothing(sweepm) ? "unknown" : sweepm[1]
fixturem = match(r"% fixture: (.+)", valsrc)
FIXTURE_NOTE = isnothing(fixturem) ? "" : "% Fixture status: $(fixturem[1]).\n"

# Parse definitions: reported values, convergence values, and display conventions.
defs = Dict{String,String}()
order = String[]
for vfile in
    (VALS, CONVERGENCE_VALS, RIDGE_VALS, ABLATION_VALS, ASSESSMENT_ACCESS_VALS, FIGMETA),
    line in eachline(vfile)

    m = match(r"^\\pvDefine\{([^}]+)\}\{(.*)\}\s*$", line)
    isnothing(m) && continue
    haskey(defs, m[1]) &&
        fail("duplicate definition of pv key '$(m[1])' in $(basename(vfile))")
    defs[m[1]] = m[2]
    push!(order, m[1])
end
isempty(defs) && fail("no \\pvDefine entries found")

# parse titles and captions (hand-edited; one ptitle + one pcaption block per figure)
capsrc = read(CAPS, String)
caps = Dict{String,String}()
for m in eachmatch(r"\\begin\{pcaption\}\{(\w+)\}\s*(.*?)\s*\\end\{pcaption\}"s, capsrc)
    haskey(caps, m[1]) && fail("duplicate pcaption block '$(m[1])' in captions.tex")
    caps[m[1]] = m[2]
end
isempty(caps) && fail("no pcaption blocks found in captions.tex")
titles = Dict{String,String}()
for m in eachmatch(r"\\begin\{ptitle\}\{(\w+)\}\s*(.*?)\s*\\end\{ptitle\}"s, capsrc)
    haskey(titles, m[1]) && fail("duplicate ptitle block '$(m[1])' in captions.tex")
    titles[m[1]] = m[2]
end
isempty(titles) && fail("no ptitle blocks found in captions.tex")

# read source, dropping full-line comments (source-file commentary, not content)
src = join([l for l in eachline(SRC) if !startswith(lstrip(l), "%")], "\n")

# inject titles and captions, checking references both ways
for (cmd, defs_d, klen) in (("pvcaption", caps, 12), ("pvtitle", titles, 10))
    refs_c = Set(m[1] for m in eachmatch(Regex("\\\\$cmd\\{(\\w+)\\}"), src))
    undef_c = sort(collect(setdiff(refs_c, keys(defs_d))))
    unused_c = sort(collect(setdiff(keys(defs_d), refs_c)))
    isempty(undef_c) ||
        fail("\\$cmd references with no block in captions.tex: " * join(undef_c, ", "))
    isempty(unused_c) ||
        fail("captions.tex $cmd blocks never referenced: " * join(unused_c, ", "))
    global src = replace(
        src, Regex("\\\\$cmd\\{(\\w+)\\}") => m -> defs_d[m[klen:(end - 1)]]
    )
end

# Resolve supplementary figure references from their order in the TeX source.
supplement_source = join(
    [line for line in eachline(SUPPLEMENT) if !startswith(lstrip(line), "%")], "\n"
)
supplement_labels = Dict{String,String}()
for (number, block) in
    enumerate(eachmatch(r"\\begin\{figure\}(.*?)\\end\{figure\}"s, supplement_source))
    labels = collect(eachmatch(r"\\label\{([^}]+)\}", block[1]))
    length(labels) == 1 || fail("each supplementary figure must have one label")
    label = only(labels)[1]
    haskey(supplement_labels, label) && fail("duplicate supplementary figure label: $label")
    supplement_labels[label] = "S$number"
end
src = replace(
    src,
    r"\\ref\{fig:supp-[^}]+\}" =>
        reference -> begin
            label = reference[6:(end - 1)]
            haskey(supplement_labels, label) ||
                fail("unknown supplementary figure: $label")
            supplement_labels[label]
        end,
)

# cross-check references vs definitions
refs = Set(m[1] for m in eachmatch(r"\\pv\{([^}]+)\}", src))
undef = sort(collect(setdiff(refs, keys(defs))))
unused = sort(collect(setdiff(keys(defs), refs)))
isempty(undef) || fail("undefined \\pv references: " * join(undef, ", "))
isempty(unused) || println("Unquoted retained values: " * join(unused, ", "))

# figure files must exist
figs = [m[1] for m in eachmatch(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}", src)]
for f in figs
    isfile(joinpath(GENERATED, f)) || fail("missing figure file: $f")
end

# flatten ("\pv{" is 4 characters, so the key is m[5:end-1])
flat = replace(
    src,
    r"\\pv\{([^}]+)\}" => m -> begin
        key = m[5:(end - 1)]
        display_value(key, defs[key])
    end,
)
occursin("\\pv{", flat) && fail("unflattened \\pv reference remains")

source_state = if REPORTING_PROVENANCE.source_clean
    "clean manuscript sources"
else
    "uncommitted manuscript/build changes included"
end
header = """
% results_section.tex: GENERATED, do not edit.
% Built by scripts/paper/build_section.jl on $(Dates.format(now(), "yyyy-mm-dd HH:MM"))
% from section_source.tex + captions.tex + values.tex + convergence/values.tex +
% Ridge, ablation, and assessment-access values + figmeta.tex + supplement figure order;
% sweep $SWEEP; each input retains its own analysis provenance below.
% manuscript commit $(REPORTING_PROVENANCE.commit); $source_state.
$(FIXTURE_NOTE)% Every number was computed from the saved sweep data by the reporting scripts.
% Display: estimates at most two decimals; percentages rounded to whole points.
% Exact parameter settings retain their source precision.
"""
header *= sprint() do io
    for input in INPUT_PROVENANCE
        println(io, "% Input: ", input.path, "; SHA256: ", input.sha256)
        for (label, commit) in input.commits
            println(io, "% Input commit: ", input.path, "; ", label, ": ", commit)
        end
    end
    for figure in figs
        println(io, "% Figure SHA256: ", figure, " ",
            bytes2hex(sha256(read(joinpath(GENERATED, figure)))))
    end
    write_source_provenance(io, REPORTING_PROVENANCE)
end
mkpath(GENERATED)
write(OUT, header * flat * "\n")
println("wrote $OUT ($(length(refs)) values inlined, $(length(figs)) figures)")

# Compile smoke test in a temporary directory.
mktempdir() do build
    wrapper = joinpath(build, "wrapper.tex")
    write(
        wrapper,
        """
\\documentclass[11pt]{article}
\\usepackage[letterpaper,margin=1in]{geometry}
\\usepackage{amsmath,amssymb,graphicx,booktabs}
\\usepackage[font=small,labelfont=bf]{caption}
\\graphicspath{{$(GENERATED)/}}
% preview readability only (this wrapper is a smoke test, not the real paper):
% separate paragraphs by a blank line instead of an indent
\\setlength{\\parskip}{0.8\\baselineskip}
\\setlength{\\parindent}{0pt}
\\begin{document}
\\input{$OUT}
\\end{document}
""",
    )
    log_path = joinpath(build, "pdflatex.out")
    ok = true
    for _ in 1:2   # two passes for \\ref
        process = run(
            pipeline(
                ignorestatus(
                    Cmd(
                        `pdflatex -interaction=nonstopmode -halt-on-error wrapper.tex`;
                        dir=build,
                    ),
                );
                stdout=log_path,
                stderr=log_path,
            );
            wait=true,
        )
        ok &= success(process)
    end
    log = read(log_path, String)
    nerr = count("\n!", log)
    pages = match(r"Output written on wrapper\.pdf \((\d+) page", log)
    ok || fail("pdflatex compile check failed")
    nerr == 0 || fail("$nerr LaTeX errors in compile check")
    println("compile check OK: $(isnothing(pages) ? "?" : pages[1]) pages, 0 errors")
end
